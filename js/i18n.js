let currentLang = localStorage.getItem('nfrp_dir_lang') || 'ne';

function setLanguage(lang) {
  if (lang !== 'ne' && lang !== 'en') lang = 'ne';
  currentLang = lang;
  localStorage.setItem('nfrp_dir_lang', lang);
  document.documentElement.lang = lang;
  
  // Update toggle buttons in UI
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.dataset.lang === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Apply translations to elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Apply translations to elements with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Re-render portals if app is initialized
  if (window.app && typeof window.app.renderPortals === 'function') {
    window.app.renderPortals();
    window.app.renderHotlines();
    if (typeof window.app.renderTickerContent === 'function') {
      window.app.renderTickerContent();
    }
  }
}

function t(key) {
  return (translations[currentLang] && translations[currentLang][key]) || key;
}

window.i18n = {
  getLang: () => currentLang,
  setLanguage,
  t,
  translations
};
